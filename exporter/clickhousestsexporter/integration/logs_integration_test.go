func TestLogsExporter_WritesAnActiveResourceOncePerRefreshInterval(t *testing.T) {
	ch := startLogStorage(t)
	exporter := startLogsExporter(t, ch.exporterConfig())
	for i := 0; i < 3; i++ {
		require.NoError(t, exporter.PushLogsData(context.Background(), testLogs()))
	}
	require.Equal(t, uint64(9), ch.count(t, "SELECT count() FROM %s.otel_logs_v1"))
	require.Equal(t, uint64(1), ch.count(t, "SELECT count() FROM %s.otel_logs_resources_v1"))
}

func TestLogsExporter_ResourceRowsCollapseAcrossWriters(t *testing.T) {
	ch := startLogStorage(t)
	for i := 0; i < 2; i++ {
		if i > 0 {
			time.Sleep(1100 * time.Millisecond)
		}
		exporter := startLogsExporter(t, ch.exporterConfig())
		require.NoError(t, exporter.PushLogsData(context.Background(), testLogs()))
	}
	require.Equal(t, uint64(2), ch.count(t,
		"SELECT uniqExact(toUnixTimestamp(Timestamp)) FROM %s.otel_logs_resources_v1"))
	require.Len(t, ch.resources(t), 1)
}

func TestLogsExporter_DropsOnlyRecordsWithoutEitherClock(t *testing.T) {
	ch := startLogStorage(t)
	exporter := startLogsExporter(t, ch.exporterConfig())
	logs := testLogs()
	records := logs.ResourceLogs().At(0).ScopeLogs().At(0).LogRecords()
	for i := 0; i < records.Len(); i++ {
		records.At(i).SetTimestamp(0)
		records.At(i).SetObservedTimestamp(0)
	}
	require.NoError(t, exporter.PushLogsData(context.Background(), logs))
	require.Equal(t, uint64(0), ch.count(t, "SELECT count() FROM %s.otel_logs_v1"))
	require.Equal(t, uint64(0), ch.count(t, "SELECT count() FROM %s.otel_logs_resources_v1"))
	require.Equal(t, uint64(0), ch.count(t, "SELECT count() FROM %s.otel_logs_trace_lookup_v1"))
}

func TestLogsExporter_NormalizesServiceBeforeResourceHash(t *testing.T) {
	ch := startLogStorage(t)
	exporter := startLogsExporter(t, ch.exporterConfig())
	logs := testLogs()
	attrs := logs.ResourceLogs().At(0).Resource().Attributes()
	attrs.Remove("service.name")
	require.NoError(t, exporter.PushLogsData(context.Background(), logs))
	attrs.PutStr("service.name", "unknown_service")
	require.NoError(t, exporter.PushLogsData(context.Background(), logs))
	require.Equal(t, uint64(6), ch.count(t, "SELECT count() FROM %s.otel_logs_v1"))
	require.Equal(t, uint64(1), ch.count(t, "SELECT uniqExact(ResourceRef) FROM %s.otel_logs_v1"))
	resources := ch.resources(t)
	require.Len(t, resources, 1)
	require.Equal(t, "unknown_service", resources[0].Strings["service.name"])
	for _, row := range ch.logs(t) {
		require.Equal(t, "unknown_service", row.ServiceName)
		require.Equal(t, resources[0].ResourceRef, row.ResourceRef)
	}
}

func TestLogsExporter_ResourceFailurePreventsFactsAndRemainsRetryable(t *testing.T) {
	ch := startLogStorage(t)
	exporter := startLogsExporter(t, ch.exporterConfig())
	_, err := ch.db.Exec(fmt.Sprintf("RENAME TABLE %s.otel_logs_resources_v1 TO %s.hidden_resources", ch.database, ch.database))
	require.NoError(t, err)
	require.ErrorContains(t, exporter.PushLogsData(context.Background(), testLogs()), "insert log resources")
	require.Equal(t, uint64(0), ch.count(t, "SELECT count() FROM %s.otel_logs_v1"))
	_, err = ch.db.Exec(fmt.Sprintf("RENAME TABLE %s.hidden_resources TO %s.otel_logs_resources_v1", ch.database, ch.database))
	require.NoError(t, err)
	require.NoError(t, exporter.PushLogsData(context.Background(), testLogs()))
	require.Len(t, ch.logs(t), 3)
	require.Len(t, ch.resources(t), 1)
}

