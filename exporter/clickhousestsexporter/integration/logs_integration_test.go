func TestLogsExporter_RejectsInvalidRecordWithoutLosingValidBatch(t *testing.T) {
	ch := startLogStorage(t)
	exporter := startLogsExporter(t, ch.exporterConfig())
	logs, err := (&plog.JSONUnmarshaler{}).UnmarshalLogs([]byte(`{"resourceLogs":[{"scopeLogs":[{"logRecords":[{
		"timeUnixNano":"1793707200123456789",
		"body":{"stringValue":"invalid"},
		"attributes":[{"key":"dup","value":{"intValue":"1"}},{"key":"dup","value":{"stringValue":"1"}}]
	}]}]}]}`))
	require.NoError(t, err)
	testLogs().ResourceLogs().At(0).CopyTo(logs.ResourceLogs().AppendEmpty())
	err = exporter.PushLogsData(context.Background(), logs)
	require.ErrorContains(t, err, `resource group 0 scope group 0 record 0: duplicate attribute key "dup"`)
	require.True(t, consumererror.IsPermanent(err))
	var rejected consumererror.Logs
	require.True(t, errors.As(err, &rejected))
	require.Equal(t, 1, rejected.Data().LogRecordCount())
	rows := ch.logs(t)
	require.Len(t, rows, 3)
	require.NotContains(t, rows, "invalid")
	require.Len(t, ch.resources(t), 1)
}
