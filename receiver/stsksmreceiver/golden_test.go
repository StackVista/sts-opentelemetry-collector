type goldenSeries struct {
	Metric string   `json:"metric"`
	Host   string   `json:"host"`
	Tags   []string `json:"tags"`
	Value  float64  `json:"value"`
}

func (s goldenSeries) key() string {
	return s.Metric + "\x00" + s.Host + "\x00" + strings.Join(s.Tags, "\x00")
}

// goldenSender keeps one gauge per name, host and tag set, the last, as the
// agent aggregator does. Service checks are dropped, as the agent serializer
// drops them.
type goldenSender struct {
	series map[string]goldenSeries
}

func (s *goldenSender) Gauge(metric string, value float64, hostname string, tags []string) {
	sorted := slices.Compact(slices.Sorted(slices.Values(tags)))
	series := goldenSeries{Metric: metric, Host: hostname, Tags: sorted, Value: value}
	s.series[series.key()] = series
}

func (*goldenSender) ServiceCheck(string, servicecheck.ServiceCheckStatus, string, []string, string) {
}

// testdata/golden.json holds the series the cluster agent's
// kubernetes_state_core check sends for testdata/objects.json, generated by
// testdata/agentgolden/generate.sh. The receiver must send the same series.
func TestSeriesMatchClusterAgent(t *testing.T) {
	data, err := os.ReadFile("testdata/golden.json")
	require.NoError(t, err)
	var want []goldenSeries
	require.NoError(t, json.Unmarshal(data, &want))
	resources, objects := loadGoldenFixture(t)

	// The fake clientset does not send the bookmark that ends a watch-list stream.
	t.Setenv("KUBE_FEATURE_WatchListClient", "false")
	cfg, ok := createDefaultConfig().(*Config)
	require.True(t, ok)
	cfg.ClusterName = "golden_cluster"
	rcv, err := newReceiver(receivertest.NewNopSettings(component.MustNewType(typeStr)), cfg, consumertest.NewNop())
	require.NoError(t, err)
	client := fake.NewClientset(objects...)
	discovery, ok := client.Discovery().(*fakediscovery.FakeDiscovery)
	require.True(t, ok)
	discovery.Resources = resources
	rcv.clusterID, err = lookupClusterID(t.Context(), client, time.Second)
	require.NoError(t, err)

	s := &goldenSender{}
	// The bubble's clock stands still while the informers fill the stores, as
	// it does in the agent harness, so durations and ages match.
	synctest.Test(t, func(t *testing.T) {
		start := time.Now()
		ctx, cancel := context.WithCancel(context.Background())
		t.Cleanup(func() {
			cancel()
			// Outlast the match-timeout clock that KSM's allowlist starts in regexp2.
			time.Sleep(2 * time.Minute)
		})
		check := rcv.newCheck()
		stores, err := check.BuildStores(ctx, client)
		require.NoError(t, err)
		synctest.Wait()
		s.series = map[string]goldenSeries{}
		check.Collect(s, stores, time.Now())
		require.Equal(t, start, time.Now(), "the clock moved")
	})

	wantByKey := map[string]goldenSeries{}
	for _, series := range want {
		wantByKey[series.key()] = series
	}
	for key, series := range wantByKey {
		got, ok := s.series[key]
		switch {
		case !ok:
			t.Errorf("missing %s %q %v = %v", series.Metric, series.Host, series.Tags, series.Value)
		case got.Value != series.Value:
			t.Errorf("value of %s %q %v is %v, want %v", series.Metric, series.Host, series.Tags, got.Value, series.Value)
		}
	}
	for key, series := range s.series {
		if _, ok := wantByKey[key]; !ok {
			t.Errorf("unexpected %s %q %v = %v", series.Metric, series.Host, series.Tags, series.Value)
		}
	}
}

func loadGoldenFixture(t *testing.T) ([]*metav1.APIResourceList, []runtime.Object) {
	t.Helper()
	raw, err := os.ReadFile("testdata/objects.json")
	require.NoError(t, err)
	var items []json.RawMessage
	require.NoError(t, json.Unmarshal(raw, &items))
	var resources []*metav1.APIResourceList
	var objects []runtime.Object
	for _, item := range items {
		var meta metav1.TypeMeta
		require.NoError(t, json.Unmarshal(item, &meta))
		if meta.Kind == "APIResourceList" {
			var list metav1.APIResourceList
			require.NoError(t, json.Unmarshal(item, &list))
			resources = append(resources, &list)
			continue
		}
		obj, _, err := scheme.Codecs.UniversalDeserializer().Decode(item, nil, nil)
		require.NoError(t, err)
		// As in the agent harness: the API server defaults suspend, and the
		// agent's KSM dereferences it.
		if cj, ok := obj.(*batchv1.CronJob); ok && cj.Spec.Suspend == nil {
			cj.Spec.Suspend = new(bool)
		}
		objects = append(objects, obj)
	}
	return resources, objects
}
